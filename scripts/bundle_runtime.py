"""Build native dependency snapshots and a complete desktop submission archive.

Capture executes on each target Python/OS and installs only hash-checked public
wheels into a temporary directory. Bundle combines the captured profiles without
running provider CLIs, collecting credentials or modifying the standard package.
"""

from __future__ import annotations

import argparse
from email.parser import BytesParser
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

from build_release import PLUGIN, ROOT, ReleaseError, SECRET_PATTERNS, read_package, validate
from runtime_bootstrap import runtime_tag

PROFILES = frozenset(f"cpython-{version}-{platform}" for version in ("310", "313")
                     for platform in ("win-amd64", "linux-x86_64"))
LOCK = PLUGIN / "requirements.lock"
MAX_FILES = 30000
MAX_RUNTIME_BYTES = 600 * 1024 * 1024


def sha(data):
    return hashlib.sha256(data).hexdigest()


def dependency_secret(data):
    # Crypto libraries legitimately contain key-format header constants. A
    # header followed by base64 key material is the credential signal here.
    pem = rb"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----\r?\n[A-Za-z0-9+/=]{20,}"
    return bool(re.search(pem, data) or any(re.search(pattern, data) for pattern in SECRET_PATTERNS[1:]))


def archive(path, files):
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zipped:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zipped.writestr(info, data, compresslevel=9)


def capture(output):
    tag = runtime_tag()
    if tag not in PROFILES:
        raise ReleaseError(f"Unverified runtime build profile: {tag}")
    uv = shutil.which("uv")
    if not uv:
        raise ReleaseError("uv is required to capture hashed wheel dependencies")
    with tempfile.TemporaryDirectory(prefix="astra runtime build ") as raw:
        packages = Path(raw) / "site-packages"
        subprocess.run([uv, "--no-config", "pip", "install", "--python", sys.executable,
                        "--target", str(packages), "--require-hashes", "--only-binary", ":all:",
                        "--default-index", "https://pypi.org/simple", "-r", str(LOCK)], check=True, timeout=300)
        files = {}
        for path in sorted(packages.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(packages)
            # Console entry points contain interpreter-specific absolute paths;
            # the gateway uses modules, so they are not distributed. Avoid
            # generated bytecode and installer caches as well.
            if (relative.parts[0] in {"bin", "Scripts", "__pycache__"}
                    or "__pycache__" in relative.parts or path.suffix in {".pyc", ".pyo"}
                    or path.name in {"RECORD", "uv_cache.json", "direct_url.json"}):
                continue
            if path.is_symlink():
                raise ReleaseError("Runtime snapshot contains a symlink")
            data = path.read_bytes()
            if dependency_secret(data):
                raise ReleaseError(f"Credential-shaped dependency content: {relative.as_posix()}")
            files["site-packages/" + relative.as_posix()] = data
        distributions = []
        for metadata in sorted(packages.glob("*.dist-info/METADATA")):
            fields = BytesParser().parsebytes(metadata.read_bytes())
            prefix = "site-packages/" + metadata.parent.name + "/"
            licenses = [name for name in files if name.startswith(prefix)
                        and ("license" in name.lower() or "copying" in name.lower() or "notice" in name.lower())]
            distributions.append({"name": fields["Name"], "version": fields["Version"],
                                  "declared_license": (fields.get("License-Expression") or fields.get("License") or "unspecified")[:300],
                                  "license_files": licenses})
        if not any(item["name"].lower() == "mcp" and item["version"] == "1.29.1" for item in distributions):
            raise ReleaseError("MCP SDK missing from captured runtime")
        info = {"format_version": 1, "tag": tag, "sdk_version": "1.29.1",
                "lock_sha256": sha(LOCK.read_bytes().replace(b"\r\n", b"\n")),
                "packages": distributions,
                "files": {name: sha(data) for name, data in sorted(files.items())}}
        files["runtime-info.json"] = (json.dumps(info, indent=2, sort_keys=True) + "\n").encode()
        output.mkdir(parents=True, exist_ok=True)
        target = output / f"runtime-{tag}.zip"
        archive(target, files)
    return {"runtime": tag, "archive": str(target), "sha256": sha(target.read_bytes()),
            "packages": len(distributions), "bytes": target.stat().st_size}


def load_snapshot(path):
    with zipfile.ZipFile(path) as zipped:
        infos = zipped.infolist()
        if len(infos) > MAX_FILES or sum(item.file_size for item in infos) > MAX_RUNTIME_BYTES:
            raise ReleaseError("Runtime snapshot exceeds bounded size limits")
        if len({item.filename for item in infos}) != len(infos):
            raise ReleaseError("Duplicate runtime paths")
        files = {}
        for item in infos:
            name = item.filename
            parsed = PurePosixPath(name)
            if (parsed.is_absolute() or "\\" in name or ":" in name
                    or any(part in {"", ".", ".."} for part in name.split("/"))
                    or name != "runtime-info.json" and not name.startswith("site-packages/")
                    or item.external_attr >> 16 & 0o170000 == 0o120000):
                raise ReleaseError("Unsafe runtime snapshot path")
            files[name] = zipped.read(item)
    info = json.loads(files.pop("runtime-info.json"))
    if (info.get("format_version") != 1 or info.get("tag") not in PROFILES
            or info.get("sdk_version") != "1.29.1"
            or info.get("lock_sha256") != sha(LOCK.read_bytes().replace(b"\r\n", b"\n"))
            or info.get("files") != {name: sha(data) for name, data in sorted(files.items())}):
        raise ReleaseError("Runtime snapshot profile, lock or content hash mismatch")
    files["runtime-info.json"] = (json.dumps(info, indent=2, sort_keys=True) + "\n").encode()
    return info, files


def bundle(runtimes, output, require_all=True):
    entries = json.loads((ROOT / "release-files.json").read_text(encoding="utf-8"))
    files = read_package(PLUGIN, entries)
    manifest = validate(files)
    profiles = {}
    for snapshot in sorted(runtimes.glob("runtime-*.zip")):
        info, contents = load_snapshot(snapshot)
        tag = info["tag"]
        if tag in profiles:
            raise ReleaseError("Duplicate bundled runtime profile")
        profiles[tag] = info
        files.update({f"runtime/{tag}/{name}": data for name, data in contents.items()})
    if not profiles or require_all and set(profiles) != PROFILES:
        raise ReleaseError("The public bundled release requires all four tested runtime profiles")
    config = json.loads(files["mcp.json"])
    config["mcpServers"]["luna_gateway"]["args"] = ["-I", "${PLUGIN_ROOT}/runtime_bootstrap.py", "luna_gateway.py"]
    files["mcp.json"] = (json.dumps(config, indent=2) + "\n").encode()
    files["runtime_bootstrap.py"] = (ROOT / "scripts/runtime_bootstrap.py").read_bytes().replace(b"\r\n", b"\n")
    files["RUNTIME.md"] = (
        "# Bundled Python runtime\n\n"
        "This archive includes hashed-wheel Python dependencies and their original license files.\n"
        "It requires a normal CPython 3.10 or 3.13 interpreter on Windows x64 or Linux x64.\n"
        "Other Python versions/platforms can use the standard uv-bootstrap package.\n"
        "Python, Codex, Antigravity and provider accounts are supplied by the user.\n"
        "Gateway startup uses the matching packaged modules without a dependency download;\n"
        "model inference still needs normal authenticated provider access.\n"
        "Debug and free-threaded interpreter builds are not supported by these profiles.\n"
        "The plugin remains MIT; third-party dependencies retain their own licenses.\n"
        f"\nIncluded profiles: {', '.join(sorted(profiles))}.\n"
    ).encode()
    output.mkdir(parents=True, exist_ok=True)
    stem = f"astra-antigravity-{manifest['version']}-bundled-runtime"
    target = output / f"{stem}.zip"
    archive(target, files)
    inventory = output / f"{stem}.inventory.json"
    inventory.write_text(json.dumps({"version": manifest["version"], "runtime_profiles": sorted(profiles),
                                    "packages_by_profile": {tag: info["packages"] for tag, info in profiles.items()},
                                    "files": {name: sha(data) for name, data in sorted(files.items())}},
                                   indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    (output / "SHA256SUMS.runtime").write_text(
        "".join(f"{sha(path.read_bytes())}  {path.name}\n" for path in (target, inventory)),
        encoding="utf-8", newline="\n")
    return {"archive": str(target), "sha256": sha(target.read_bytes()), "runtime_profiles": sorted(profiles),
            "complete_profiles": set(profiles) == PROFILES,
            "file_count": len(files), "bytes": target.stat().st_size, "official_submission_ready": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    capture_parser = commands.add_parser("capture")
    capture_parser.add_argument("--output", type=Path, default=ROOT / "dist/runtimes")
    bundle_parser = commands.add_parser("bundle")
    bundle_parser.add_argument("--runtimes", type=Path, required=True)
    bundle_parser.add_argument("--output", type=Path, default=ROOT / "dist")
    bundle_parser.add_argument("--allow-partial", action="store_true", help="Local testing only; release builds require all profiles")
    args = parser.parse_args()
    result = capture(args.output) if args.action == "capture" else bundle(args.runtimes, args.output, not args.allow_partial)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
